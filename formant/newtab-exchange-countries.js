const PRIMARY_COUNTRY = new Map();
for (const row of EXCHANGE_COUNTRY_MAP) {
  if (!PRIMARY_COUNTRY.has(row.code)) PRIMARY_COUNTRY.set(row.code, row.country);
}

export function primaryExchangeCountry(code) {
  return PRIMARY_COUNTRY.get(code) || "";
}

/**
 * Empty query lists currencies in catalog order, with the primary country.
 * A query matches country, code, or currency name, and can return several countries for one code.
 * @param {string} query
 * @param {Array<{ code: string, name: string }>} currencies
 * @param {Set<string>} blocked
 */
export function searchExchangePlaces(query, currencies, blocked) {
  const q = String(query || "").trim().toLowerCase();
  const nameOf = new Map(currencies.map((item) => [item.code, item.name]));
  if (!q) {
    return currencies
      .filter((item) => !blocked.has(item.code))
      .map((item) => ({
        country: primaryExchangeCountry(item.code),
        code: item.code,
        name: item.name,
      }));
  }
  const hits = [];
  for (const row of EXCHANGE_COUNTRY_MAP) {
    if (blocked.has(row.code)) continue;
    const name = nameOf.get(row.code) || "";
    const hay = `${row.country} ${row.code} ${name}`.toLowerCase();
    if (hay.includes(q)) hits.push({ country: row.country, code: row.code, name });
  }
  return hits;
}
