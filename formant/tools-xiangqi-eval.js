function pieceScore(piece, x, y) {
  const red = isRed(piece);
  const type = piece.toUpperCase();
  const table = PST[type];
  const row = red ? 9 - y : y;
  let value = PIECE_VALUE[piece] || 0;
  if (table) value += table[row][x] || 0;
  if (type === "P" && ((red && y < 5) || (!red && y > 4))) value += 50;
  return value;
}

/** 正分表示 sideToMove 优势。叶子只算子力+位置，不做走法生成。 */
export function evaluate(board, sideToMove) {
  let red = 0;
  let black = 0;
  for (let y = 0; y < RANKS; y++) {
    for (let x = 0; x < FILES; x++) {
      const piece = board[y][x];
      if (!piece) continue;
      const score = pieceScore(piece, x, y);
      if (isRed(piece)) red += score;
      else black += score;
    }
  }
  const diff = red - black;
  return sideToMove === BLACK ? -diff : diff;
}
